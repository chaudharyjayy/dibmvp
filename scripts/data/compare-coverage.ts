/**
 * compare-coverage — what we hold, what the catalogue holds, and what the
 * labels actually gave us.
 *
 * This is the comparison the data work needs: for every drug the engine
 * lists, show whether the catalogue knows it, whether a label was found, which
 * parameters that label actually stated, and what the database currently
 * exposes to the simulator.
 *
 * Usage:
 *   npm run data:compare
 *   npm run data:compare -- --json
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createClient } from '@supabase/supabase-js';
import { readRepoEnv, repoRoot } from './lib/env';
import { canonicalName } from './lib/names';

const CACHE = join(repoRoot, 'data', '.cache', 'labels');
const INDEX = join(CACHE, 'index.json');
const EVIDENCE = join(repoRoot, 'data', 'pk-evidence.csv');
const INTERACTIONS = join(repoRoot, 'data', 'interactions.candidates.csv');
const OUT = join(repoRoot, 'data', 'coverage-report.md');

type EngineDrug = {
  id: string;
  name: string;
  route: string;
  ka_per_h: number | null;
  F: number | null;
  CL_L_per_h_per_kg: number | null;
  V_L_per_kg: number | null;
};

function readCsv(path: string): Array<Record<string, string>> {
  if (!existsSync(path)) return [];
  const text = readFileSync(path, 'utf8');
  const lines = text.split('\n').filter((line) => line.trim());
  if (!lines.length) return [];
  const split = (line: string): string[] => {
    const cells: string[] = [];
    let current = '';
    let quoted = false;
    for (const char of line) {
      if (char === '"') quoted = !quoted;
      else if (char === ',' && !quoted) {
        cells.push(current);
        current = '';
      } else current += char;
    }
    cells.push(current);
    return cells;
  };
  const header = split(lines[0]);
  return lines.slice(1).map((line) => {
    const cells = split(line);
    const row: Record<string, string> = {};
    header.forEach((name, index) => {
      row[name] = cells[index] ?? '';
    });
    return row;
  });
}

async function main(): Promise<void> {
  const env = readRepoEnv();
  const engine = JSON.parse(readFileSync(join(repoRoot, 'data', 'drugs.json'), 'utf8')) as EngineDrug[];
  const evidence = readCsv(EVIDENCE);
  const interactions = readCsv(INTERACTIONS);
  const labels = existsSync(INDEX)
    ? (JSON.parse(readFileSync(INDEX, 'utf8')) as { rows: Array<{ drug: string; citationUrl: string | null; pkChars: number; interactionChars: number; dailymedVerified: boolean | null }> }).rows
    : [];

  let catalogue = new Map<string, { id: string; name: string; pkStatus: string; productCount: number }>();
  let exposed: Array<Record<string, unknown>> = [];
  if (env.SUPABASE_URL && env.SUPABASE_ANON_KEY) {
    const db = createClient(env.SUPABASE_URL, env.SUPABASE_ANON_KEY, { auth: { persistSession: false } });
    // Supabase returns at most 1,000 rows per request, so the catalogue is
    // paged: a single call would silently miss most ingredients.
    const pageSize = 1000;
    for (let from = 0; ; from += pageSize) {
      const { data, error } = await db
        .from('drugs')
        .select('id,name,pk_status,product_count')
        .range(from, from + pageSize - 1);
      if (error || !data) break;
      for (const entry of data) catalogue.set(canonicalName(entry.name), entry);
      if (data.length < pageSize) break;
    }
    console.log(`catalogue rows read: ${catalogue.size}`);
    const { data: pk } = await db.from('drug_pk_public').select('*');
    exposed = pk ?? [];
  }

  const lines: string[] = [];
  lines.push('# Coverage: engine list, catalogue, labels, database');
  lines.push('');
  lines.push(`Generated by \`npm run data:compare\` on ${new Date().toISOString().slice(0, 10)}.`);
  lines.push('');
  lines.push('| engine drug | catalogue | label found | label says | exposed to simulator |');
  lines.push('| --- | --- | --- | --- | --- |');

  for (const drug of engine) {
    const key = canonicalName(drug.name);
    const catalogueRow = catalogue.get(key);
    const label = labels.find((row) => canonicalName(row.drug) === key);
    const params = evidence
      .filter((row) => canonicalName(row.drug) === key)
      .map((row) => row.parameter.replace(/_l_per_h_per_kg|_per_h|_l_per_kg|_h$/, '').replace(/_/g, ' '));
    const exposedRow = exposed.find((row) => canonicalName(String(row.drug_id)) === key);
    lines.push(
      `| ${drug.name} (\`${drug.id}\`) | ${
        catalogueRow
          ? `yes — ${catalogueRow.id}, ${catalogueRow.product_count} products`
          : '**no**'
      } | ${
        label
          ? `yes — ${label.citationUrl ? 'DailyMed' : 'none'}${label.dailymedVerified ? ', citation verified' : ''}`
          : 'no'
      } | ${
        params.length ? [...new Set(params)].join(', ') : 'nothing'
      } | ${
        exposedRow
          ? `**yes — approved row with ${exposedRow.source_url ? 'a citation' : 'no citation'}**`
          : 'no'
      } |`
    );
  }

  lines.push('');
  lines.push('## Parameters the engine still needs');
  lines.push('');
  lines.push('| drug | ka | F | CL | V | dose range |');
  lines.push('| --- | --- | --- | --- | --- | --- |');
  for (const drug of engine) {
    const key = canonicalName(drug.name);
    const have = (name: string) => evidence.some((row) => canonicalName(row.drug) === key && row.parameter === name);
    lines.push(
      `| ${drug.name} | ${have('ka_per_h') ? 'cited' : '**missing**'} | ${
        have('f_bioavailability') ? 'cited' : '**missing**'
      } | ${have('cl_l_per_h_per_kg') ? 'cited' : '**missing**'} | ${
        have('v_l_per_kg') ? 'cited' : '**missing**'
      } | **missing** |`
    );
  }

  lines.push('');
  lines.push('## Interaction candidates found in the labels');
  lines.push('');
  if (interactions.length) {
    lines.push('| drug A | drug B | suggested severity |');
    lines.push('| --- | --- | --- |');
    for (const row of interactions) {
      lines.push(`| ${row.drug_a} | ${row.drug_b} | ${row.suggested_severity} |`);
    }
    lines.push('');
    lines.push('Suggested only. `data/interactions.json` stays empty until a human checks each pair.');
  } else {
    lines.push('None yet. Run `npm run data:labels` then `npm run data:interactions:candidates`.');
  }

  writeFileSync(OUT, lines.join('\n') + '\n');
  console.log(lines.join('\n'));
  console.log(`\nwrote ${OUT}`);
}

main().catch((error) => {
  console.error((error as Error).message);
  process.exitCode = 1;
});
